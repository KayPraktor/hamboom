-- ═══ چرا این پلن ═══════════════════════════════════════════════════════════
--
-- هر کاربر هنگامِ ثبت‌نام یک تیمِ `is_personal` می‌گیرد (`services/accounts.ts`). این تیم
-- هیچ اشتراکی ندارد، پس رزولوشنِ پلن `COALESCE(s.plan_code, 'free')` به آن **پلنِ رایگان**
-- می‌داد — یعنی لحظه‌ای که گیتِ ظرفیت روشن شود، **هر کاربر روی ۳ بوردِ شخصی سقف می‌خورد**.
--
-- ★★ **چرا این غلط بود (تصمیمِ مالک، ۱۴۰۵/۰۶/۱۵):**
--
--   ۱. **دیواری بدونِ در.** پلن‌های `pro`/`team` صندلی‌محور و برای تیم‌اند. «اشتراکِ حرفه‌ای
--      برای فضای شخصی‌ات بخر» چیزی است که اصلاً طراحی نشده. پس کاربری که به آن سقف
--      می‌خورد مسیرِ خریدی هم ندارد — فقط گیر می‌کند. سقف باید جایی باشد که ارتقا معنا دارد.
--   ۲. **تعدادِ بورد چیزی نیست که هزینه می‌زند.** یک بوردِ خالی یک ردیف است. هزینه‌ی واقعی
--      **بایتِ ذخیره‌سازی** و **حافظه‌ی اتاقِ realtime** است (اندازه‌گیریِ M2: ۷۶MB برای بوردِ
--      ۵۰۰۰عنصری). سقفِ شمارشِ بورد هزینه را کنترل نمی‌کند.
--   ۳. **محرکِ ارتقا در محصولِ همکاری، اضافه‌کردنِ هم‌تیمی است.** ارزشِ هم‌بوم وقتی دیده
--      می‌شود که کاربر کسی را دعوت کند — و همان‌جا `max_members` می‌نشیند.
--
-- ★ **چرا یک ردیفِ پلن و نه یک `if` در کد:** گیتِ ظرفیت باید **یک مسیر** بماند. با این ردیف،
--   سقف‌ها **داده** اند نه کد، و با یک `UPDATE` قابلِ تنظیم‌اند. رزولوشن در
--   `apps/api/src/dto.ts` به `CASE WHEN t.is_personal THEN 'personal' ELSE 'free' END` تبدیل
--   می‌شود — هیچ شاخه‌ی ویژه‌ای در منطقِ گیت نیست.
--
-- `-1` یعنی نامحدود (قراردادِ `planLimit`).

