-- 0007 — حذفِ `usage_counters` (M5 گام ۸٫۳)
--
-- ── چرا حذف، و نه «بعداً پرش می‌کنیم» ─────────────────────────────────────
--
-- این جدول از M3 وجود داشت تا کشِ شمارنده‌های پلن باشد، و **هرگز به‌روز نشد** —
-- باگِ B-4/B-5ی که فاز ۱ی M4 پیدایش کرد: هر ردیف صفر می‌مانْد، پس هر سقفی که به آن
-- تکیه می‌کرد عملاً بی‌اثر بود. تصمیمِ M4
-- ([ADR-053](../../../ARCHITECTURE_DECISIONS.md#adr-053)) این بود که ظرفیت با
-- `count(*)`ِ **واقعی** خوانده شود، و از آن روز این جدول نه نوشته می‌شد نه خوانده.
--
-- ⚠️ **یک جدولِ مرده بی‌ضرر نیست.** تا وقتی هست، هر کسی که schema را بخواند فرض
-- می‌کند منبعِ معتبرِ مصرف است، و اولین کسی که برای «بهینه‌سازی» از آن بخوانَد،
-- عددِ **صفر** می‌گیرد و سقف را بی‌صدا باز می‌کند. دقیقاً همان کلاسِ نقصی که
-- `devAuthEnvSchema` در فاز ۴ داشت: مرده بود، پس حذف شد تا وجودش تخلف باشد.
--
-- ⊕ پیش از این migration، دو نوشتنِ باقی‌مانده (`routes/teams.ts` و
--   `services/accounts.ts`) برداشته شدند؛ آن دو تنها ردیفِ خالی درج می‌کردند.
--
-- ⚠️ **این migration برگشت‌ناپذیر است** و همین درست است: ADR-005 می‌گوید migrationِ
--    اجراشده تغییرناپذیر است، پس اگر روزی کشِ شمارنده لازم شد، جدولی **تازه** با
--    منطقِ به‌روزرسانیِ واقعی ساخته می‌شود — نه احیای این.
--
-- ⛔ **`audit_logs` عمداً دست‌نخورده می‌مانَد.** آن هم امروز هیچ نویسنده‌ای ندارد، ولی
--    تفاوتش اساسی است: `usage_counters` **جایگزین شده** (شمارشِ زنده)، در حالی که
--    audit هنوز پیاده نشده و پنلِ ادمینِ M6 مصرف‌کننده‌اش است. حذفِ چیزی که هنوز
--    نیامده با حذفِ چیزی که کنار گذاشته شده یکی نیست.
-- ══════════════════════════════════════════════════════════════════════════

DROP TABLE IF EXISTS usage_counters;
