import type pg from "pg";

/**
 * ★★ انتخابِ رهبر با advisory lockِ Postgres — M5 گام ۶٫۱
 * ([ADR-060](../../../../ARCHITECTURE_DECISIONS.md#adr-060)).
 *
 * ── ⚠️ این قفل برای **درستی** نیست، برای **اتلاف** است ────────────────────
 *
 * و اشتباه‌گرفتنِ این دو خطرناک است. درستیِ «دو تسویه‌ی هم‌زمان ⇒ یک اشتراک» از **قفلِ
 * ردیفِ** `payments` می‌آید ([ADR-050](../../../../ARCHITECTURE_DECISIONS.md#adr-050)/
 * [ADR-055](../../../../ARCHITECTURE_DECISIONS.md#adr-055))، و سنجه‌ی
 * `billing:probe-reconcile` با برداشتنِ `FOR UPDATE` قرمز می‌شود. این‌جا فقط جلوی این را
 * می‌گیریم که سه نود **سه برابر** به درگاه تماس بزنند.
 *
 * ⚠️ **پس اگر روزی این قفل خراب شد، سیستم پول را دوبار فعال نمی‌کند** — فقط بی‌جهت شلوغ
 * می‌شود. نوشتنِ این‌جا لازم است چون هر خواننده‌ای که برعکسش را فرض کند، ممکن است روزی
 * قفلِ ردیف را «چون قفلِ رهبر داریم» بردارد.
 *
 * ── ★★ چرا اتصالِ **اختصاصی** ─────────────────────────────────────────────
 *
 * advisory lock به **session** بسته است، نه به تراکنش و نه به استخر. سنجه‌ی
 * [`infra:probe-lock`](../../../../scripts/infra-probe-lock.ts) در فاز ۱ اندازه گرفت:
 * گرفتن روی یک اتصالِ استخر و آزادکردن روی اتصالِ **دیگر**، `false` می‌دهد و قفل
 * **می‌مانَد** — تا مرگِ آن نشست.
 *
 * ⚠️ خطرِ واقعی `pool.query` است که انتخابِ اتصال را **پنهان** می‌کند. `pool.connect()`
 * برعکس، یک اتصال را تا `release()` در اختیارِ ما می‌گذارد؛ پس قفل و آزادسازی روی
 * **همان** نشست می‌افتند. به همین دلیل این‌جا `connect()` است و هیچ‌جا `pool.query`.
 *
 * ⊕ و مرگِ نود قفل را **خودکار** آزاد می‌کند (همان سنجه اثباتش کرد) — یعنی یک crash
 * آشتی‌دهی را تا ری‌استارتِ دیتابیس نمی‌خواباند.
 */

/**
 * کلیدِ قفلِ کارِ آشتی‌دهی.
 *
 * ⚠️ **ثابت و مستند**، نه هش‌شده از یک رشته: کلیدِ هش‌شده یعنی دو نسخه‌ی کد که رشته‌شان
 * یک حرف فرق دارد، دو قفلِ متفاوت بگیرند و هر دو هم‌زمان کار کنند. هر کارِ بازه‌ایِ بعدی
 * کلیدِ **خودش** را از همین‌جا می‌گیرد.
 */
export const RECONCILE_LOCK_KEY = 811_451_001;

export interface AdvisoryLockDeps {
  pool: pg.Pool;
  key?: number;
}

/**
 * `fn` را فقط وقتی اجرا می‌کند که قفل گرفته شود؛ وگرنه `null` برمی‌گرداند.
 *
 * ★ خروجیِ `null` عمداً از «کار انجام شد ولی چیزی پیدا نکرد» **قابلِ تفکیک** است —
 * وگرنه لاگِ نودِ بازنده از لاگِ نودی که واقعاً کار کرد جدا نمی‌شود.
 */
export async function withAdvisoryLock<T>(
  deps: AdvisoryLockDeps,
  fn: () => Promise<T>,
): Promise<T | null> {
  const key = deps.key ?? RECONCILE_LOCK_KEY;
  // ★ اتصالِ اختصاصی — دلیلش در صدرِ فایل. `pool.query` این‌جا **غلط** است.
  const client = await deps.pool.connect();
  let held = false;
  try {
    const { rows } = await client.query<{ locked: boolean }>(
      "SELECT pg_try_advisory_lock($1) AS locked",
      [key],
    );
    held = rows[0]?.locked === true;
    if (!held) return null;
    return await fn();
  } finally {
    if (held) {
      // ⚠️ آزادسازی نباید خطای خودش را به بیرون بدهد: اگر اتصال از قبل مرده باشد،
      //    قفل **از قبل** آزاد شده و انداختنِ خطا فقط شکستِ واقعیِ کار را می‌پوشانَد.
      await client
        .query("SELECT pg_advisory_unlock($1)", [key])
        .catch(() => undefined);
    }
    client.release();
  }
}
