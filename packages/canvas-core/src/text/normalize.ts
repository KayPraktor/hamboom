/**
 * نرمال‌سازی ورودی فارسی.
 *
 * **چرا لازم است:** spike گام ۱٫۳ب ثابت کرد موتور رندر `ي`/`ك` عربی را به
 * `ی`/`ک` فارسی تبدیل **نمی‌کند** — متن پیست‌شده از منبع عربی‌زبان یا کیبورد
 * عربی عیناً می‌ماند. این دو کاراکتر از نظر بصری تقریباً یکسان‌اند ولی code
 * point متفاوتی دارند، پس جستجو و مقایسه‌ی رشته‌ای شکست می‌خورد.
 *
 * ⚠️ **این یک قرارداد بین‌ماژولی است، نه یک کمک‌تابع محلی.**
 *
 * اگر فقط اینجا (در ویرایشگر بوم) نرمال‌سازی کنیم، متنی که از مسیرهای دیگر
 * وارد می‌شود — API، قالب‌ها، seed دیتابیس، import — نرمال‌نشده می‌ماند و در
 * جستجوی ماژول M3 با متن فارسی مچ نمی‌شود.
 *
 * **تصمیم لازم قبل از شروع M3:** آیا این تابع به `packages/shared-types`
 * منتقل شود تا backend هم از همان استفاده کند؟ تا آن موقع اینجا می‌ماند و
 * هیچ ماژول دیگری به آن وابسته نمی‌شود.
 *
 * @see ../../../../TODO.md گام ۱٫۴
 */

/** نگاشت کاراکترهای عربی به معادل فارسی‌شان. */
const ARABIC_TO_PERSIAN: ReadonlyMap<string, string> = new Map([
  ["ي", "ی"], // ي عربی → ی فارسی
  ["ى", "ی"], // ى الف مقصوره → ی فارسی
  ["ك", "ک"], // ك عربی → ک فارسی
  ["ڪ", "ک"], // ڪ → ک
  ["ة", "ه"], // ة تاء مربوطه → ه
  ["ؤ", "و"], // ؤ → و (بدون همزه در املای رایج فارسی)
]);

/** ارقام عربی‌ـهندی (۰۶۶۰) و عربی شرقی (۰۶F0) → ارقام فارسی. */
const ARABIC_INDIC_DIGITS = /[٠-٩]/g;
const EXTENDED_ARABIC_DIGITS = /[۰-۹]/g;

/** اعراب و علائم تشکیل — عمداً **حذف نمی‌شوند** (پایین را بخوان). */
const TATWEEL = /ـ+/g;

export interface NormalizeOptions {
  /** تبدیل ي/ك و مشابه به معادل فارسی. پیش‌فرض: روشن. */
  arabicLetters?: boolean;
  /** حذف کشیده (tatweel) که فقط تزئینی است. پیش‌فرض: روشن. */
  tatweel?: boolean;
  /**
   * یکسان‌سازی ارقام به فارسی. پیش‌فرض: **خاموش**.
   *
   * عمداً خاموش است: کاربر ممکن است رقم لاتین را عمداً تایپ کرده باشد
   * (شماره نسخه، کد، شناسه). تبدیل خودکارش داده‌ی کاربر را عوض می‌کند.
   * برای جستجو، نرمال‌سازی در لایه‌ی جستجو انجام می‌شود، نه روی متن ذخیره‌شده.
   */
  digits?: boolean;
}

/**
 * نرمال‌سازی متن فارسی برای ذخیره و مقایسه.
 *
 * **آنچه عمداً انجام نمی‌دهد:**
 * - اعراب (فتحه، کسره، ...) را حذف نمی‌کند — در متن قرآنی و آموزشی معنادارند
 *   و حذفشان داده‌ی کاربر را از بین می‌برد.
 * - نیم‌فاصله (ZWNJ) را دست نمی‌زند — بخشی از املای درست فارسی است.
 * - فاصله‌های تکراری را جمع نمی‌کند — ممکن است عمدی باشند (چیدمان روی بوم).
 * - ارقام را به‌صورت پیش‌فرض تبدیل نمی‌کند (بالا را بخوان).
 */
export function normalizePersian(text: string, options: NormalizeOptions = {}): string {
  const { arabicLetters = true, tatweel = true, digits = false } = options;

  let result = text;

  if (arabicLetters) {
    let mapped = "";
    for (const char of result) mapped += ARABIC_TO_PERSIAN.get(char) ?? char;
    result = mapped;
  }

  if (tatweel) {
    result = result.replace(TATWEEL, "");
  }

  if (digits) {
    result = result
      .replace(ARABIC_INDIC_DIGITS, (d) => String.fromCharCode(d.charCodeAt(0) - 0x0660 + 0x06f0))
      .replace(EXTENDED_ARABIC_DIGITS, (d) => d);
  }

  return result;
}

/**
 * نسخه‌ی تهاجمی‌تر — فقط برای **کلید جستجو**، هرگز برای ذخیره.
 * اعراب را حذف و ارقام را یکسان می‌کند تا «کتاب» و «کِتاب» و «۱۲۳» و «123»
 * یکدیگر را پیدا کنند.
 */
export function persianSearchKey(text: string): string {
  return normalizePersian(text)
    .replace(/[ً-ْٰـ]/g, "") // اعراب و کشیده
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x06f0)) // ارقام فارسی → لاتین
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x0660)) // ارقام عربی → لاتین
    .replace(/‌/g, " ") // نیم‌فاصله → فاصله
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}
