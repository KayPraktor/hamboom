/**
 * نرمال‌سازی متن فارسی — **قرارداد مشترک بین ماژول‌ها**.
 *
 * ── چرا اینجاست، نه در canvas-core ────────────────────────────────────
 *
 * spike گام ۱٫۳ب ثابت کرد موتور رندر `ي`/`ك` عربی را به `ی`/`ک` فارسی تبدیل
 * **نمی‌کند** — متن پیست‌شده از منبع عربی‌زبان یا کیبورد عربی عیناً می‌ماند.
 * این دو کاراکتر از نظر بصری تقریباً یکسان‌اند ولی code point متفاوتی دارند،
 * پس جستجو و مقایسه‌ی رشته‌ای شکست می‌خورد.
 *
 * مسئله در **مرز ماژول‌ها** است، نه داخل بوم: متن از چند مسیر وارد سیستم
 * می‌شود — بوم، API، قالب‌ها، seed دیتابیس، import. اگر هر کدام قاعده‌ی خودش
 * را داشته باشد، «كتابي» که از API آمده هرگز با «کتابی» که کاربر تایپ کرده
 * مچ نمی‌شود. پس یک پیاده‌سازی، در پایین‌ترین لایه.
 *
 * **مصرف‌کننده‌ها:** `canvas-core` (ورودی بوم)، `backend-api` (ذخیره و جستجو
 * در M3)، `realtime-sync` (متن ورودی از شبکه).
 *
 * ── ⚠️ کجا صدا زده شود ────────────────────────────────────────────────
 *
 * **نه روی هر ضربه‌ی کیبورد.** باگ U-1 در `patches/README.md` نشان می‌دهد وقتی
 * نرمال‌سازی طول رشته را عوض کند و مکان‌نما بازگردانده نشود، مکان‌نما می‌پرد.
 * `normalizePersian` با گزینه‌های پیش‌فرض می‌تواند طول را عوض کند (حذف کشیده).
 *
 * جای درست صدا زدنش:
 * - هنگام **پیست** (یک‌بار، مکان‌نما به انتهای متن پیست‌شده می‌رود)
 * - هنگام **ذخیره / commit عنصر** (کاربر دیگر در حال تایپ نیست)
 * - هنگام **import** از API یا قالب
 *
 * برای جستجو از `persianSearchKey` استفاده کن، نه از این.
 */

/** نگاشت کاراکترهای عربی به معادل فارسی‌شان. */
const ARABIC_TO_PERSIAN: ReadonlyMap<string, string> = new Map([
  ["ي", "ی"], // ي عربی → ی فارسی
  ["ى", "ی"], // ى الف مقصوره → ی فارسی
  ["ك", "ک"], // ك عربی → ک فارسی
  ["ڪ", "ک"], // ڪ → ک
  ["ة", "ه"], // ة تاء مربوطه → ه
  ["ؤ", "و"], // ؤ → و (بدون همزه در املای رایج فارسی)
]);

/** ارقام عربی‌ـهندی (U+0660) و عربی شرقی/فارسی (U+06F0). */
const ARABIC_INDIC_DIGITS = /[٠-٩]/g;
const PERSIAN_DIGITS = /[۰-۹]/g;

/** کشیده — فقط تزئینی است و معنا را عوض نمی‌کند. */
const TATWEEL = /ـ+/g;

/** اعراب و علائم تشکیل. */
const DIACRITICS = /[ً-ٰٟ]/g;

/** نیم‌فاصله. */
const ZWNJ = /‌/g;

export interface NormalizeOptions {
  /** تبدیل ي/ك و مشابه به معادل فارسی. پیش‌فرض: روشن. */
  arabicLetters?: boolean;
  /** حذف کشیده (tatweel). پیش‌فرض: روشن. ⚠️ طول رشته را عوض می‌کند. */
  tatweel?: boolean;
  /**
   * یکسان‌سازی ارقام به فارسی. پیش‌فرض: **خاموش**.
   *
   * عمداً خاموش است: کاربر ممکن است رقم لاتین را عمداً تایپ کرده باشد
   * (شماره نسخه، کد، شناسه). تبدیل خودکارش داده‌ی کاربر را عوض می‌کند.
   * برای جستجو، نرمال‌سازی در `persianSearchKey` انجام می‌شود، نه روی
   * متن ذخیره‌شده.
   */
  digits?: boolean;
}

/**
 * نرمال‌سازی متن فارسی برای ذخیره و مقایسه.
 *
 * **آنچه عمداً انجام نمی‌دهد:**
 * - اعراب (فتحه، کسره، ...) را حذف نمی‌کند — در متن قرآنی و آموزشی معنادارند
 *   و حذفشان داده‌ی کاربر را از بین می‌برد.
 * - نیم‌فاصله (ZWNJ) را دست نمی‌زند — بخشی از املای درست فارسی است.
 * - فاصله‌های تکراری را جمع نمی‌کند — ممکن است عمدی باشند (چیدمان روی بوم).
 * - ارقام را به‌صورت پیش‌فرض تبدیل نمی‌کند.
 */
export function normalizePersian(text: string, options: NormalizeOptions = {}): string {
  const { arabicLetters = true, tatweel = true, digits = false } = options;

  let result = text;

  if (arabicLetters) {
    let mapped = "";
    for (const char of result) mapped += ARABIC_TO_PERSIAN.get(char) ?? char;
    result = mapped;
  }

  if (tatweel) {
    result = result.replace(TATWEEL, "");
  }

  if (digits) {
    result = result.replace(ARABIC_INDIC_DIGITS, (d) =>
      String.fromCharCode(d.charCodeAt(0) - 0x0660 + 0x06f0),
    );
  }

  return result;
}

/**
 * کلید جستجو — تهاجمی‌تر، **هرگز برای ذخیره**.
 *
 * اعراب را حذف و ارقام را یکسان می‌کند تا «کتاب» و «کِتاب»، و «۱۲۳» و «123»
 * یکدیگر را پیدا کنند. در M3 روی ستون جستجوی Postgres اعمال می‌شود.
 */
export function persianSearchKey(text: string): string {
  return normalizePersian(text)
    .replace(DIACRITICS, "")
    .replace(PERSIAN_DIGITS, (d) => String(d.charCodeAt(0) - 0x06f0))
    .replace(ARABIC_INDIC_DIGITS, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(ZWNJ, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}
