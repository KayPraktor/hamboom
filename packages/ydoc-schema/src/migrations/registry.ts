import type * as Y from "yjs";

/**
 * رجیستریِ **ترتیبیِ** migrationهای ساختارِ سند — [PLAN بخش ۷٫۵](../../../../PLAN.md).
 *
 * ── چطور یکی اضافه می‌شود ─────────────────────────────────────────────
 *
 * ۱. `SCHEMA_VERSION` در [`doc.ts`](../doc.ts) را یکی بالا ببر.
 * ۲. یک ورودیِ تازه با `from = نسخه‌ی قبلی` و `to = نسخه‌ی نو` **به انتهای** این
 *    آرایه اضافه کن.
 * ۳. تابع را **تنها روی خودِ سند** بنویس — هیچ I/O، هیچ شبکه، هیچ زمانِ جاری.
 *    این کد روی سندی اجرا می‌شود که ممکن است ماه‌ها بعد از دیتابیس بیرون بیاید و
 *    باید هر بار **همان** نتیجه را بدهد.
 * ۴. هرگز یک ورودیِ منتشرشده را ویرایش نکن. دیتابیس‌هایی وجود دارند که آن نسخه را
 *    قبلاً رد کرده‌اند و دوباره اجرا نمی‌شود — همان دلیلی که گیتِ checksum برای
 *    migrationهای SQL گذاشته شد (گام ۰٫۳).
 *
 * ⚠️ `migrateDocument` خودش بررسی می‌کند که این زنجیره **پیوسته** باشد و به
 * `SCHEMA_VERSION` برسد. یک migrationِ اضافه‌شده بدونِ بالابردنِ `SCHEMA_VERSION`
 * (یا برعکس) خطا می‌دهد، نه سکوت.
 */
export interface Migration {
  /** نسخه‌ای که این migration از آن شروع می‌کند. */
  from: number;
  /** همیشه `from + 1` — پرش ممنوع است تا زنجیره قابلِ بازرسی بماند. */
  to: number;
  /** یک جمله که در لاگِ بارگذاریِ اتاق می‌نشیند. */
  describe: string;
  migrate(doc: Y.Doc): void;
}

